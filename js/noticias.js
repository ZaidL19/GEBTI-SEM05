const modal =
document.getElementById("modal-noticia");

const tituloModal =
document.getElementById("titulo-modal");

const imagenModal =
document.getElementById("imagen-modal");

const textoModal =
document.getElementById("texto-modal");

const btnCerrar =
document.getElementById("btn-cerrar");

const botonesAbrir =
document.querySelectorAll(".btn-abrir");

/* ========================= */
/* ABRIR MODAL */
/* ========================= */

botonesAbrir.forEach(boton => {

    boton.addEventListener("click", () => {

        const id =
        boton.getAttribute("data-id");

        const info =
        datosNoticias[id];

        tituloModal.textContent =
        info.titulo;

        imagenModal.src =
        info.imagen;

        textoModal.textContent =
        info.contenido;

        modal.showModal();

    });

});

/* ========================= */
/* CERRAR MODAL */
/* ========================= */

btnCerrar.addEventListener("click", () => {

    modal.close();

});